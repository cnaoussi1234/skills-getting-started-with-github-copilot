def test_unregister_removes_all_matching_participant_entries(client):
    # Arrange
    activity_name = "Chess Club"
    encoded_activity_name = quote(activity_name, safe="")
    email = "duplicate-student@mergington.edu"
    app_module.activities[activity_name]["participants"].extend([email, email])
    app_module.activities["Programming Class"]["participants"].append(email)

    # Act
    response = client.delete(
        f"/activities/{encoded_activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert response.json() == {"message": f"Unregistered {email} from {activity_name}"}
    assert email not in app_module.activities[activity_name]["participants"]
    assert email in app_module.activities["Programming Class"]["participants"]


